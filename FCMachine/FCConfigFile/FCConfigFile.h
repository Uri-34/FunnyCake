#ifndef FC_CONFIG_FILE_H
#define FC_CONFIG_FILE_H

#include <QString>
#include <QStringList>
#include <QSettings>
#include <QCoreApplication>
#include <QDir>
#include <QFileInfo>

/**
 * @brief Класс-одиночка (Singleton) для централизованного управления конфигурацией приложения.
 *
 * Предоставляет доступ к путям файловых ресурсов, расширениям файлов и списку серийных номеров
 * подключённых устройств (плоттеров). Использует QSettings в формате INI для персистентного
 * хранения настроек.
 *
 * Расположение конфигурационного файла:
 *   - На десктопных системах: рядом с исполняемым файлом (<имя_программы>.conf),
 *   - На встраиваемых системах (Raspberry Pi с Buildroot): в /etc/funnycake/ или /usr/local/etc/,
 *   - При отсутствии прав на запись: в директории пользователя (QStandardPaths).
 *
 * Особенности реализации:
 *   - Строгая реализация паттерна Singleton (запрещено копирование и перемещение),
 *   - Ленивая инициализация при первом обращении к instance(),
 *   - Автоматическое создание значений по умолчанию при отсутствии конфигурационного файла,
 *   - Поддержка горячей перезагрузки конфигурации через методы load()/save().
 *
 * @warning Класс НЕ является потокобезопасным — все операции должны выполняться
 *          в основном потоке приложения. Для многопоточного доступа используйте
 *          внешнюю синхронизацию (например, QMutex).
 * @note Для встраиваемых систем с ограничениями файловой системы (только чтение, RAMFS):
 *       - При невозможности записи конфигурация сохраняется только в памяти,
 *       - Рекомендуется вызывать save() только при наличии подтверждённой возможности записи.
 * @see QSettings для деталей реализации персистентного хранения
 */
class FCConfigFile
{
public:
    /// @brief Возвращает единственный экземпляр класса (ленивая инициализация).
    /// @return Ссылка на глобальный экземпляр конфигурации.
    /// @note Экземпляр создаётся при первом вызове и живёт до завершения программы.
    ///       Потокобезопасность гарантируется только в C++11 и выше (стандартное поведение
    ///       для статических локальных переменных).
    [[nodiscard]] static FCConfigFile& instance();

    /// @brief Деструктор (освобождает ресурсы при завершении программы).
    /// @note Автоматически вызывается при завершении приложения. Явный вызов невозможен
    ///       из-за приватности деструктора в классическом Singleton (здесь разрешён для
    ///       совместимости с современными практиками).
    ~FCConfigFile() = default;

    // --- геттеры конфигурации (только для чтения) ---
    /// @brief Возвращает расширение файлов моделей.
    /// @return Строка ".svg" (включая точку).
    /// @note Расширение определено на этапе компиляции и не может быть изменено во время выполнения.
    [[nodiscard]] const QString& modelExtension() const noexcept { return _modelExtension; }

    /// @brief Возвращает расширение файлов управляющего кода.
    /// @return Строка ".code" (включая точку).
    /// @note Расширение определено на этапе компиляции и не может быть изменено во время выполнения.
    [[nodiscard]] const QString& codeExtension() const noexcept { return _codeExtension; }

    /// @brief Возвращает расширение конфигурационного файла.
    /// @return Строка ".conf" (включая точку).
    /// @note Расширение определено на этапе компиляции и не может быть изменено во время выполнения.
    [[nodiscard]] const QString& configExtension() const noexcept { return _configExtension; }

    /// @brief Возвращает путь к каталогу с файлами моделей.
    /// @return Абсолютный путь к директории моделей (например, "/usr/share/funnycake/models").
    /// @note Путь нормализован (без завершающего слеша). При отсутствии конфигурации
    ///       возвращается значение по умолчанию относительно расположения исполняемого файла.
    [[nodiscard]] const QString& modelsPath() const noexcept { return _modelsPath; }

    /// @brief Возвращает путь к каталогу с файлами управляющего кода.
    /// @return Абсолютный путь к директории кодов (например, "/usr/share/funnycake/codes").
    /// @note Путь нормализован (без завершающего слеша). При отсутствии конфигурации
    ///       возвращается значение по умолчанию относительно расположения исполняемого файла.
    [[nodiscard]] const QString& codesPath() const noexcept { return _codesPath; }

    /// @brief Возвращает полный путь к конфигурационному файлу.
    /// @return Абсолютный путь к файлу конфигурации (например, "/etc/funnycake/funnycake.conf").
    /// @note Путь вычисляется один раз при инициализации и не изменяется во время выполнения.
    [[nodiscard]] const QString& confPath() const noexcept { return _confPath; }

    /// @brief Возвращает список серийных номеров зарегистрированных плоттеров.
    /// @return QStringList с серийными номерами в формате "VID:PID:SERIAL" или "SERIAL".
    /// @note Список может быть пустым, если устройства ещё не были обнаружены или зарегистрированы.
    [[nodiscard]] const QStringList& plottersSerialNumbers() const noexcept { return _plotterSerialNumbers; }

    // --- методы управления конфигурацией ---
    /// @brief Принудительно перезагружает конфигурацию из файла.
    /// @note Все текущие значения (включая серийные номера) будут перезаписаны значениями из файла.
    ///       Изменения, сделанные программно и не сохранённые через save(), будут потеряны.
    void reload() { load(); }

    /// @brief Сохраняет текущее состояние конфигурации в файл.
    /// @return true, если сохранение успешно; иначе — false (например, нет прав на запись).
    /// @note На встраиваемых системах с файловой системой только для чтения метод вернёт false.
    ///       Рекомендуется проверять возвращаемое значение перед завершением работы приложения.
    [[nodiscard]] bool persist() { return save(); }

private:
    // --- ключи конфигурации (статические строковые литералы) ---
    /// Имя группы "paths" в INI-файле для хранения путей к ресурсам.
    static constexpr const char* KEY_PATHS = "paths";

    /// Ключ "models" внутри группы "paths" для пути к моделям.
    static constexpr const char* KEY_MODELS_PATH = "models";

    /// Ключ "codes" внутри группы "paths" для пути к управляющим кодам.
    static constexpr const char* KEY_CODES_PATH = "codes";

    /// Ключ "serialNumbers" в корне для списка серийных номеров устройств.
    static constexpr const char* KEY_SERIAL_NUMBERS = "serialNumbers";

    // --- расширения файлов (статические строковые литералы) ---
    /// Расширение файлов векторных моделей (формат SVG).
    static constexpr const char* MODEL_EXT = ".svg";

    /// Расширение файлов управляющего кода (собственный формат приложения).
    static constexpr const char* CODE_EXT = ".code";

    /// Расширение конфигурационного файла (формат INI).
    static constexpr const char* CONFIG_EXT = ".conf";

    // --- состояние экземпляра ---
    /// Полный путь к конфигурационному файлу (вычисляется один раз при инициализации).
    QString _confPath;

    /// Текущий путь к каталогу с файлами моделей (абсолютный, нормализованный).
    QString _modelsPath;

    /// Текущий путь к каталогу с файлами управляющего кода (абсолютный, нормализованный).
    QString _codesPath;

    /// Список серийных номеров обнаруженных/зарегистрированных плоттеров.
    QStringList _plotterSerialNumbers;

    /// Константная строка расширения файлов моделей (инициализируется один раз).
    const QString _modelExtension = QString::fromLatin1(MODEL_EXT);

    /// Константная строка расширения файлов управляющего кода (инициализируется один раз).
    const QString _codeExtension = QString::fromLatin1(CODE_EXT);

    /// Константная строка расширения конфигурационного файла (инициализируется один раз).
    const QString _configExtension = QString::fromLatin1(CONFIG_EXT);

    // --- управление жизненным циклом (паттерн Singleton) ---
    /// @brief Приватный конструктор для гарантии единственности экземпляра.
    /// @note Автоматически вызывает методы определения пути конфигурации и загрузки настроек.
    ///       При отсутствии файла конфигурации создаются значения по умолчанию.
    FCConfigFile();

    /// @brief Запрещает копирование экземпляра (паттерн Singleton).
    FCConfigFile(const FCConfigFile&) = delete;

    /// @brief Запрещает присваивание экземпляра (паттерн Singleton).
    FCConfigFile& operator=(const FCConfigFile&) = delete;

    // --- внутренние вспомогательные методы ---
    /// @brief Определяет и возвращает путь к конфигурационному файлу.
    /// @return Абсолютный путь к файлу конфигурации.
    /// @note Алгоритм поиска:
    ///       1. Рядом с исполняемым файлом (<appname>.conf),
    ///       2. В /etc/funnycake/ (для систем на базе Buildroot),
    ///       3. В /usr/local/etc/funnycake/ (альтернативное системное расположение),
    ///       4. В директории пользователя (как резервный вариант).
    [[nodiscard]] QString determineConfigPath() const;

    /// @brief Загружает настройки из конфигурационного файла или создаёт значения по умолчанию.
    /// @note При отсутствии файла или ошибке чтения используются пути относительно
    ///       расположения исполняемого файла:
    ///       - модели: <appdir>/../share/funnycake/models
    ///       - коды:   <appdir>/../share/funnycake/codes
    void load();

    /// @brief Сохраняет текущие настройки в конфигурационный файл.
    /// @return true при успешной записи; иначе — false.
    /// @note Метод не создаёт родительские директории — они должны существовать заранее.
    ///       На системах только для чтения (например, squashfs) всегда возвращает false.
    bool save();
};

#endif // FC_CONFIG_FILE_H
