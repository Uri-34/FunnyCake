/// @brief Список сырых указателей на последовательные устройства.
/// @details Удобный тип для управления группой устройств в менеджерах или очередях.
/// @note Управление временем жизни объектов должно быть внешним (например, через
///       родительскую иерархию QObject или умные указатели).
/// @see FCSerialDeviceQList для безопасных слабых ссылок
using FCSerialDeviceList = QList<FCSerialDevice *>;

/// @brief Список безопасных слабых ссылок (QPointer) на последовательные устройства.
/// @details QPointer автоматически обнуляется при уничтожении объекта, что предотвращает
///          обращение к освобождённой памяти в сигналах/слотах или асинхронных операциях.
/// @note Рекомендуется для хранения в UI-слое, таймерах или наблюдателях.
/// @warning Не используйте для владения объектом — только для наблюдения.
using FCSerialDeviceQList = QList<QPointer<FCSerialDevice>>;

