#ifndef FC_NOZZLE_H
#define FC_NOZZLE_H

#include <QtGlobal>
#include <QList>
#include <cmath>
#include <QColor>

/**
 * @brief Класс для описания параметров отдельного сопла печатающей головки.
 *
 * Представляет физическое сопло плоттера с геометрическими и гидродинамическими характеристиками:
 *   - Позиция сопла в локальной системе координат головки (мм),
 *   - Диаметр отверстия сопла (мм),
 *   - Скорость потока материала (мм³/с).
 *
 * Особенности реализации:
 *   - Является простым классом данных для максимальной эффективности,
 *   - Не содержит логики управления — только хранение параметров,
 *   - Поддерживает тривиальную копируемость (trivially copyable) для использования в контейнерах и сериализации.
 *
 * Типичные конфигурации сопел в промышленных плоттерах:
 *   - Тонкое сопло: диаметр 0.2–0.4 мм для детализированных линий и текста,
 *   - Среднее сопло: диаметр 0.5–0.7 мм для универсального нанесения,
 *   - Широкое сопло: диаметр 1.0–2.0 мм для быстрой заливки больших площадей.
 *
 * @warning Критически важно:
 *          - Диаметр сопла ДОЛЖЕН быть строго положительным (> 0) — нулевой или отрицательный
 *            диаметр приведёт к делению на ноль при расчёте площади сечения,
 *          - Позиция сопла задаётся в локальной системе координат головки, а не в глобальной
 *            системе плоттера — преобразование координат выполняется внешними компонентами.
 * @note Для встраиваемых систем (Raspberry Pi 4 + Buildroot):
 *       - Класс занимает ровно 24 байта (2×float для позиции + 2×float для диаметра/потока)
 *         на 32-битных платформах, что оптимально для выравнивания памяти,
 *       - Все операции с экземплярами структуры являются максимально эффективными (без виртуальных вызовов,
 *         динамического выделения памяти или сложной логики),
 *       - Рекомендуется передавать экземпляры по константной ссылке в функции для избегания копирования.
 * @see FCHead для управления группой сопел в составе печатающей головки
 * @see FCPlotter для использования сопел в процессе нанесения изображений
 */
class FCNozzle
{
public:
    /// @brief Конструктор с параметрами.
    /// @param pos Позиция центра сопла в локальной системе координат головки (мм).
    /// @param diam Диаметр отверстия сопла (мм). Должен быть > 0.
    /// @param rate Скорость потока материала (мм³/с). Может быть 0 для неактивного сопла.
    /// @note При передаче недопустимого диаметра (≤ 0) автоматически устанавливается значение 0.1 мм
    ///       для предотвращения деления на ноль в расчётах.
    constexpr FCNozzle(const QColor &color = QColor(), float diameter = 0.4f, float rate = 0.0f) noexcept
        : _color{color}, // цвет
          _diameter{diameter > 0.0f ? diameter : 1.0f},  // защита от недопустимого диаметра
          _flowRate{rate >= 0.0f ? rate : 0.1f} // защита от отрицательного потока
    {}

    inline QColor& color() { return _color; }

    // --- методы доступа и расчёта ---
    /// @brief Возвращает площадь поперечного сечения сопла (мм²).
    /// @return Значение π × (диаметр/2)².
    /// @note Используется для расчёта объёма подаваемого материала и скорости движения головки.
    [[nodiscard]] constexpr float crossSectionArea() const noexcept
    {
        const float radius = _diameter * 0.5f;
        return static_cast<float>(M_PI) * radius * radius;
    }

    /// @brief Возвращает теоретическую скорость движения материала на выходе из сопла (мм/с).
    /// @return Значение потока / площадь сечения.
    /// @note При нулевой площади сечения возвращает 0.0 для предотвращения деления на ноль.
    [[nodiscard]] constexpr float materialVelocity() const noexcept
    {
        const float area = crossSectionArea();
        return (area > 0.0f) ? (_flowRate / area) : 0.0f;
    }

    /// @brief Проверяет валидность параметров сопла.
    /// @return true если диаметр > 0 и поток ≥ 0; иначе — false.
    [[nodiscard]] constexpr bool isValid() const noexcept
    {
        return _diameter > 0.0f && _flowRate >= 0.0f;
    }

    // --- операторы сравнения ---
    /// @brief Оператор сравнения на равенство.
    /// @param other Другое сопло для сравнения.
    /// @return true если все поля идентичны с точностью до 0.01 мм; иначе — false.
    /// @note Используется допуск 0.01 мм для учёта ошибок округления при расчётах с плавающей точкой.
    [[nodiscard]] bool operator==(const FCNozzle &other) const noexcept
    {
        constexpr float tolerance = 0.01f;
        return _color == other._color &&
               std::abs(_diameter - other._diameter) <= tolerance &&
               std::abs(_flowRate - other._flowRate) <= tolerance;
    }

    /// @brief Оператор сравнения на неравенство.
    /// @param other Другое сопло для сравнения.
    /// @return true если сопла различаются хотя бы по одному параметру; иначе — false.
    [[nodiscard]] inline bool operator!=(const FCNozzle &other) const noexcept
    {
        return !(*this == other);
    }

    /// @brief Метод возвращающий диаметр.
    [[nodiscard]] inline float diameter() const noexcept
    {
        return _diameter;
    }

private:
    // --- поля данных (публичные для максимальной эффективности) ---
    QColor _color;
    /// Диаметр отверстия сопла (мм). Должен быть строго положительным (> 0).
    /// Определяет толщину наносимой линии и расход материала.
    float _diameter;

    /// Скорость потока материала через сопло (мм³/с).
    /// Зависит от давления в системе подачи, вязкости материала и диаметра сопла.
    /// Значение 0.0 означает отсутствие подачи (сопло заблокировано или неактивно).
    float _flowRate;
};

// --- псевдонимы типов ---
/// Список сопел для хранения конфигурации печатающей головки.
using FCNozzleList = QList<FCNozzle>;

/// Вектор сопел для математических операций и трансформаций.
using FCNozzleVector = QVector<FCNozzle>;

// Гарантирует предсказуемый размер структуры для эффективной упаковки в памяти
static_assert(sizeof(FCNozzle) <= 32, "Размер FCNozzle не должен превышать 32 байта для оптимальной упаковки");

#endif // FC_NOZZLE_H
